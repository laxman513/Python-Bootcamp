import numpy as np

numbers = ([10, 20, 30, 40, 50, 60])

print("Arrays:", numbers)

print("Elements from index 1 to 3:", numbers[1:4])

print("First 3 Elements:", numbers[:3])

print("Elements from index 2:", numbers[2:])

print("Every 2nd Element:", numbers[::2])

print("Elements from starting to before last index:", numbers[:-1])

print("Reverse array:", numbers[::-1])
